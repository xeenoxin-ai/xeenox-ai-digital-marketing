let toastTimer;
export function toast(msg, tone = '') {
  let el = $('#toast');
  if (!el) { el = document.createElement('div'); el.id = 'toast'; el.setAttribute('role', 'status'); document.body.append(el); }
  el.className = `toast show ${tone}`;
  el.textContent = msg;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => el.classList.remove('show'), 2600);
}

/** Modal dialog. Returns { el, close }. `onClose` runs once. */
export function modal(title, body, { wide = false, onClose } = {}) {
  const wrap = document.createElement('div');
  wrap.className = 'modal-wrap';
  wrap.innerHTML = `<div class="modal ${wide ? 'wide' : ''}" role="dialog" aria-modal="true" aria-label="${esc(title)}">
    <header><h2>${esc(title)}</h2><button class="icon-btn" data-close aria-label="Close">${icon('x')}</button></header>
    <div class="modal-body">${body}</div></div>`;
  document.body.append(wrap);
  document.body.classList.add('has-modal');
  let closed = false;
  const close = () => {
    if (closed) return;
    closed = true;
    wrap.remove();
    if (!$('.modal-wrap')) document.body.classList.remove('has-modal');
    document.removeEventListener('keydown', onKey);
    onClose?.();
  };
  const onKey = (e) => { if (e.key === 'Escape' && wrap === $$('.modal-wrap').at(-1)) close(); };
  document.addEventListener('keydown', onKey);
  wrap.addEventListener('click', (e) => { if (e.target === wrap || e.target.closest('[data-close]')) close(); });
  setTimeout(() => $('input:not([type=hidden]),select,textarea,button.primary', wrap.querySelector('.modal-body'))?.focus(), 30);
  return { el: wrap, close };
}

export function confirmBox(text, { ok = 'Yes', danger = false } = {}) {
  return new Promise((res) => {
    const m = modal('Please confirm', `<p>${esc(text)}</p><div class="row end"><button class="btn" data-close>Cancel</button><button class="btn ${danger ? 'danger' : 'primary'}" id="cfOk">${esc(ok)}</button></div>`, { onClose: () => res(false) });
    $('#cfOk', m.el).onclick = () => { res(true); m.close(); };
  });
}

export function download(name, text, type = 'application/json') {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(new Blob([text], { type }));
  a.download = name;
  document.body.append(a);
  a.click();
  setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 500);
}

export async function copyText(text) {
  try { await navigator.clipboard.writeText(text); return true; } catch {
    const t = document.createElement('textarea');
    t.value = text; document.body.append(t); t.select();
    const ok = document.execCommand('copy'); t.remove(); return ok;
  }
}

